// Bundles db/migrations/*.sql into a TypeScript module so migrations ship inside the server build
// (serverless hosts don't include loose .sql files). Runs automatically before `build` and `test`.
import fs from "node:fs";
import path from "node:path";

const dir = path.resolve("db/migrations");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(path.join(dir, f), "utf8"))} },`).join("\n");
const out = `// GENERATED by scripts/embed-migrations.mjs from db/migrations/*.sql — do not edit by hand.\nexport const EMBEDDED_MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`;
const target = path.resolve("src/lib/db/migrations.generated.ts");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) fs.writeFileSync(target, out);
console.log(`embedded ${files.length} migrations`);
